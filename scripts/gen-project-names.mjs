// Writes api/_lib/projectNames.ts: every project's name in the four languages, for server
// emails sent without a browser (the day-before tour reminder of api/daily.ts). Runs with
// `npm run build`; commit the file it writes.
import { readFileSync, writeFileSync } from "node:fs";

const LOCALES = ["en", "ar", "fr", "ru"];
const dicts = Object.fromEntries(LOCALES.map((l) => [l, JSON.parse(readFileSync(new URL(`../src/i18n/${l}.json`, import.meta.url), "utf8"))]));
const names = {};
for (const slug of Object.keys(dicts.en.projectsData)) {
  names[slug] = Object.fromEntries(LOCALES.map((l) => [l, dicts[l].projectsData?.[slug]?.name ?? dicts.en.projectsData[slug].name]));
}
const out = `// Generated by scripts/gen-project-names.mjs from src/i18n/*.json — do not edit by hand.
export const PROJECT_NAMES: Record<string, Record<"en" | "ar" | "fr" | "ru", string>> = ${JSON.stringify(names, null, 2)};
`;
const file = new URL("../api/_lib/projectNames.ts", import.meta.url);
let current = "";
try {
  current = readFileSync(file, "utf8");
} catch {
  // first run
}
if (current !== out) writeFileSync(file, out);
